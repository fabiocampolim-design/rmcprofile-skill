@dataclass
class DataFile:
    x: np.ndarray
    y: np.ndarray
    err: np.ndarray | None = None
    title: str = ""
    metadata: dict = field(default_factory=dict)


def _to_float(tok):
    return float(tok.replace("D", "E").replace("d", "e"))


def read_data_file(path):
    """Two-line header ('<npoints>' then a title line, then columns) or STOG
    ('# Key: value' lines, then columns). Two columns -> (x, y); three -> (x, y, err)."""
    with open(path, encoding="utf-8", errors="replace") as f:
        lines = f.read().splitlines()
    meta, title, rows = {}, "", []
    if lines and lines[0].lstrip().startswith("#"):
        i = 0
        while i < len(lines) and lines[i].lstrip().startswith("#"):
            body = lines[i].lstrip("#").strip()
            if ":" in body and not body.startswith("-"):
                k, _, v = body.partition(":")
                meta[k.strip()] = v.strip()
            i += 1
        title = meta.get("Title", "")
        data_lines = lines[i:]
    else:
        n = int(lines[0].split()[0])
        title = lines[1].rstrip()
        data_lines = lines[2:]
        if sum(1 for ln in data_lines if ln.strip()) < n:
            raise ValueError("%s: header says %d points, fewer data lines follow" % (path, n))
    for ln in data_lines:
        toks = ln.split()
        if toks and _is_number(toks[0]):
            rows.append([_to_float(t) for t in toks])
    arr = np.array(rows)
    if arr.ndim != 2 or arr.shape[1] < 2:
        raise ValueError("%s: expected at least two numeric columns" % path)
    return DataFile(arr[:, 0], arr[:, 1], arr[:, 2] if arr.shape[1] >= 3 else None, title, meta)


def write_data_file(path, x, y, title, err=None, style="two-line"):
    x, y = np.asarray(x, float), np.asarray(y, float)
    cols = [x, y] + ([np.asarray(err, float)] if err is not None else [])
    body = ["  " + "  ".join("%.8f" % c[i] for c in cols) for i in range(len(x))]
    if style == "two-line":
        head = [" %d" % len(x), title]
    elif style == "stog":
        head = ["# File: rmcprofile-skill data file", "# Title: %s" % title, "# Number of points: %d" % len(x),
                "# ------------------------------------"]
    else:
        raise ValueError("style must be 'two-line' or 'stog'")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(head + body) + "\n")


@dataclass
class Bragg:
    npoints: int
    bank: int
    scale: float
    volume: float
    title: str
    x: np.ndarray
    y: np.ndarray


def read_bragg(path):
    with open(path, encoding="utf-8", errors="replace") as f:
        lines = f.read().splitlines()
    n, bank, scale, vol = lines[0].split()[:4]
    n, bank = int(n), int(bank)
    rows = [[_to_float(t) for t in ln.split()[:2]] for ln in lines[2:] if ln.strip() and _is_number(ln.split()[0])]
    if len(rows) != n:
        raise ValueError("%s: header says %d points, file has %d" % (path, n, len(rows)))
    arr = np.array(rows)
    return Bragg(n, bank, _to_float(scale), _to_float(vol), lines[1].strip(), arr[:, 0], arr[:, 1])


def read_back(path):
    with open(path, encoding="utf-8", errors="replace") as f:
        toks = f.read().split()
    n = int(toks[0])
    vals = np.array([_to_float(t) for t in toks[1:1 + n]])
    if len(vals) != n:
        raise ValueError("%s: expected %d background coefficients" % (path, n))
    return vals


def read_inst(path):
    """GSAS instrument-parameter extract: '<nbanks>' then, per bank, its number on
    its own line followed by the value lines until the next bank number."""
    with open(path, encoding="utf-8", errors="replace") as f:
        lines = [ln for ln in f.read().splitlines() if ln.strip()]
    nb = int(lines[0].split()[0])
    banks, cur = [], None
    for ln in lines[1:]:
        toks = ln.split()
        if len(toks) == 1 and toks[0].isdigit():
            cur = {"bank": int(toks[0]), "values": []}
            banks.append(cur)
        elif cur is not None:
            cur["values"].extend(_to_float(t) for t in toks)
    if len(banks) != nb:
        raise ValueError("%s: header says %d banks, found %d" % (path, nb, len(banks)))
    return banks


def read_hkl(path):
    with open(path, encoding="utf-8", errors="replace") as f:
        lines = [ln.split() for ln in f.read().splitlines() if ln.strip()]
    return {"scale": _to_float(lines[0][0]),
            "ranges": [(int(a), int(b), _to_float(c)) for a, b, c in (ln[:3] for ln in lines[1:4])]}


def read_dw(path):
    with open(path, encoding="utf-8", errors="replace") as f:
        return [(int(t[0]), _to_float(t[1]), _to_float(t[2]))
                for t in (ln.split() for ln in f.read().splitlines()) if len(t) >= 3]


