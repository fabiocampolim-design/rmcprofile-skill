def read_chi2_history(path):
    """'<stem>.chi2' / '<stem>_chi2.txt': a header line of column names, then rows."""
    with open(path, encoding="utf-8", errors="replace") as f:
        lines = [ln for ln in f.read().splitlines() if ln.strip()]
    names = lines[0].split()
    rows = [[_to_float(t) for t in ln.split()] for ln in lines[1:] if _is_number(ln.split()[0])]
    arr = np.array(rows) if rows else np.zeros((0, len(names)))
    out = {}
    for j, nm in enumerate(names):
        col = arr[:, j] if arr.size else np.zeros(0)
        out[nm] = col.astype(int) if nm.startswith("m_") or nm == "moves" else col
    return out


def _read_csv_numeric(path):
    with open(path, encoding="utf-8", errors="replace") as f:
        lines = f.read().splitlines()
    header = [h.strip() for h in lines[0].split(",") if h.strip()]
    rows = []
    for ln in lines[1:]:
        toks = [t.strip() for t in ln.split(",") if t.strip()]
        if toks and _is_number(toks[0]):
            rows.append([_to_float(t) for t in toks])
    return header, np.array(rows)


def read_csv_pair(path):
    """_SQn.csv / _PDFn.csv / _bragg.csv -> (x, calculated, experiment)."""
    _, arr = _read_csv_numeric(path)
    return arr[:, 0], arr[:, 1], arr[:, 2]


def read_partials_csv(path):
    """_PDFpartials.csv / _SQnpartials.csv -> (x, {pair_label: values})."""
    header, arr = _read_csv_numeric(path)
    labels = header[1:]
    return arr[:, 0], {lab: arr[:, 1 + j] for j, lab in enumerate(labels)}
