KB_EV = 8.617333262e-5          # Boltzmann constant, eV/K


# ----------------------------------------------------------------------------
# the box
# ----------------------------------------------------------------------------
@dataclass
class Box:
    types: list
    counts: list
    lattice: np.ndarray
    frac: np.ndarray
    atoms: np.ndarray
    density: float

    @classmethod
    def from_rmc6f(cls, cfg):
        return cls(list(cfg.atom_types), list(cfg.counts), np.array(cfg.lattice, float),
                   np.array(cfg.frac, float) % 1.0, np.array(cfg.atoms, dtype=object), float(cfg.density))

    @property
    def n(self):
        return int(self.frac.shape[0])

    def cart(self):
        return self.frac @ self.lattice

    def distance_row(self, i, frac_i=None):
        """Minimum-image distances from atom i (at frac_i if given) to every atom; entry i = inf."""
        fi = self.frac[i] if frac_i is None else frac_i
        d = self.frac - fi
        d -= np.round(d)
        row = np.sqrt(((d @ self.lattice) ** 2).sum(axis=1))
        row[i] = np.inf
        return row

    def to_rmc6f(self, template):
        n = self.n
        return rt.Rmc6f(header=dict(template.header), atom_types=list(self.types), counts=list(self.counts),
                        cell=template.cell, lattice=self.lattice.copy(), supercell=template.supercell,
                        density=self.density, atoms=self.atoms.copy(), frac=self.frac.copy(),
                        site=np.array(template.site, int) if len(template.site) == n else np.zeros(n, int),
                        cellidx=(np.array(template.cellidx, int) if len(template.cellidx) == n
                                 else np.zeros((n, 3), int)),
                        banner=["(Version 6f format configuration file)", "(Generated by rmclite %s)" % rt.__version__])


def rms_displacement(box, ref):
    d = box.frac - ref.frac
    d -= np.round(d)
    return float(np.sqrt(((d @ box.lattice) ** 2).sum(axis=1).mean()))


# ----------------------------------------------------------------------------
# incremental partial histograms on RMCProfile's grid
# ----------------------------------------------------------------------------
class Histogram:
    def __init__(self, box, rmax, dr):
        L = min(np.linalg.norm(box.lattice, axis=1))
        if rmax > L / 2 + 1e-9:
            raise ValueError("rmax %.2f exceeds half the shortest cell edge (%.2f)" % (rmax, L / 2))
        self.box, self.rmax, self.dr = box, rmax, dr
        self.r, self.edges = rt.rmc_grid(rmax, dr)
        self.labels = rt.pair_labels(box.types)
        self.tindex = {t: k for k, t in enumerate(box.types)}
        self.atype = np.array([self.tindex[a] for a in box.atoms])
        self.pair_of = {}
        for i, a in enumerate(box.types):
            for j, b in enumerate(box.types):
                self.pair_of[(i, j)] = "%s-%s" % ((a, b) if i <= j else (b, a))
        V = abs(np.linalg.det(box.lattice))
        self.norm = {}
        for i, a in enumerate(box.types):
            for b in box.types[i:]:
                na, nb = box.counts[i], box.counts[box.types.index(b)]
                self.norm["%s-%s" % (a, b)] = 1.0 / (na * (nb / V) * 4 * np.pi * self.r ** 2 * dr)
        self.rebuild()

    def _bin_rows(self, i, row):
        """Histogram one atom's distance row into per-pair bin counts (pairs seen from i's side)."""
        out = {}
        mask = np.isfinite(row) & (row < self.edges[-1])
        bins = np.searchsorted(self.edges, row[mask], side="right") - 1
        ok = (bins >= 0) & (bins < len(self.r))
        bins, types = bins[ok], self.atype[mask][ok]
        ti = self.atype[i]
        for tj in range(len(self.box.types)):
            sel = types == tj
            if sel.any():
                lab = self.pair_of[(ti, tj)]
                out[lab] = out.get(lab, 0) + np.bincount(bins[sel], minlength=len(self.r))
        return out

    @staticmethod
    def _factor(lab):
        """partial_gr histograms the full n_a x n_b distance block: an unlike pair (a,b) is
        counted once (row a, column b), a like pair twice (both orderings). Summing every
        atom's row counts every pair twice, so unlike counts are halved on rebuild and a
        move touches a like pair's bins by 2 and an unlike pair's by 1."""
        a, b = lab.split("-")
        return 2 if a == b else 1

    def rebuild(self):
        self.counts = {lab: np.zeros(len(self.r), dtype=np.int64) for lab in self.labels}
        for i in range(self.box.n):
            for lab, c in self._bin_rows(i, self.box.distance_row(i)).items():
                self.counts[lab] += c
        for lab in self.labels:
            if self._factor(lab) == 1:
                self.counts[lab] //= 2

    def update(self, i, old_row, new_row):
        for lab, c in self._bin_rows(i, old_row).items():
            self.counts[lab] -= self._factor(lab) * c
        for lab, c in self._bin_rows(i, new_row).items():
            self.counts[lab] += self._factor(lab) * c

    def g(self, counts=None):
        counts = self.counts if counts is None else counts
        return {lab: counts[lab] * self.norm[lab] for lab in self.labels}


# ----------------------------------------------------------------------------
# targets (chi^2 terms) and constraints
# ----------------------------------------------------------------------------
class PartialTarget:
    def __init__(self, label, r, g, sigma):
        self.label, self.r, self.g, self.sigma = label, np.asarray(r, float), np.asarray(g, float), float(sigma)

    def chi2(self, hist, counts=None):
        assert np.allclose(hist.r, self.r), "target grid must equal the histogram grid"
        calc = hist.g(counts)[self.label]
        return float(np.sum((calc - self.g) ** 2) / self.sigma ** 2)


class TotalGTarget:
    def __init__(self, r, G, sigma, weights):
        self.r, self.G, self.sigma, self.w = np.asarray(r, float), np.asarray(G, float), float(sigma), dict(weights)

    def calc(self, hist, counts=None):
        g = hist.g(counts)
        return sum(self.w[lab] * (g[lab] - 1.0) for lab in g)

    def chi2(self, hist, counts=None):
        assert np.allclose(hist.r, self.r), "target grid must equal the histogram grid"
        return float(np.sum((self.calc(hist, counts) - self.G) ** 2) / self.sigma ** 2)


class FqTarget(TotalGTarget):
    def __init__(self, q, F, sigma, density, weights):
        self.q, self.F, self.sigma = np.asarray(q, float), np.asarray(F, float), float(sigma)
        self.density, self.w = float(density), dict(weights)

    def chi2(self, hist, counts=None):
        G = TotalGTarget.calc(self, hist, counts)
        Fc = rt.fq_from_gr(hist.r, G, self.density, self.q)
        return float(np.sum((Fc - self.F) ** 2) / self.sigma ** 2)


class ClosestApproach:
    def __init__(self, dmin):
        self.dmin = dict(dmin)

    def ok(self, hist, i, new_row):
        ti = hist.atype[i]
        for tj in range(len(hist.box.types)):
            lab = hist.pair_of[(ti, tj)]
            if lab in self.dmin:
                sel = hist.atype == tj
                if np.any(new_row[sel] < self.dmin[lab]):
                    return False
        return True


class DistanceWindow:
    """Pairs whose starting distance lies inside [rmin, rmax] for their label must stay inside."""

    def __init__(self, windows):
        self.windows = dict(windows)
        self.members = None                     # {i: [j, ...]} fixed at first use

    def _init(self, hist):
        self.members = {}
        for i in range(hist.box.n):
            row = hist.box.distance_row(i)
            for j in np.where(np.isfinite(row))[0]:
                lab = hist.pair_of[(hist.atype[i], hist.atype[j])]
                if lab in self.windows and self.windows[lab][0] <= row[j] <= self.windows[lab][1]:
                    self.members.setdefault(i, []).append(int(j))

    def ok(self, hist, i, new_row):
        if self.members is None:
            self._init(hist)
        for j in self.members.get(i, ()):
            lab = hist.pair_of[(hist.atype[i], hist.atype[j])]
            lo, hi = self.windows[lab]
            if not (lo <= new_row[j] <= hi):
                return False
        return True


class BondPotential:
    """Harmonic bond energy  U = sum 1/2 k (d - r0)^2  over pairs of `label` closer than `cutoff`,
    entering the acceptance rule as U / (k_B T)."""

    def __init__(self, label, k, r0, cutoff, T):
        self.label, self.k, self.r0, self.cutoff, self.T = label, float(k), float(r0), float(cutoff), float(T)

    def energy_row(self, hist, i, row):
        ti = hist.atype[i]
        e = 0.0
        for tj in range(len(hist.box.types)):
            if hist.pair_of[(ti, tj)] == self.label:
                d = row[(hist.atype == tj) & np.isfinite(row)]
                d = d[d < self.cutoff]
                e += 0.5 * self.k * np.sum((d - self.r0) ** 2)
        return e / (KB_EV * self.T)


# ----------------------------------------------------------------------------
# the engine
# ----------------------------------------------------------------------------
@dataclass
class RunState:
    generated: int = 0
    tested: int = 0
    accepted: int = 0
    chi2_history: list = field(default_factory=list)


class RmcLite:
    def __init__(self, box, rmax, dr, targets, constraints=(), potentials=(), max_move=None, seed=0):
        self.box = box
        self.hist = Histogram(box, rmax, dr)
        self.targets = list(targets)
        self.constraints = list(constraints)
        self.potentials = list(potentials)
        self.max_move = dict(max_move or {t: 0.05 for t in box.types})
        self.rng = np.random.default_rng(seed)
        self.inv_lattice = np.linalg.inv(box.lattice)
        self.chi2 = self._chi2(self.hist.counts)
        self.state = RunState(chi2_history=[(0, self.chi2)])

    def _chi2(self, counts):
        return sum(t.chi2(self.hist, counts) for t in self.targets)

    def step(self):
        """One move: returns True if accepted."""
        st = self.state
        st.generated += 1
        i = int(self.rng.integers(self.box.n))
        amp = self.max_move[self.box.atoms[i]]
        v = self.rng.normal(size=3)
        v *= amp * self.rng.random() / np.linalg.norm(v)
        new_frac = (self.box.frac[i] + v @ self.inv_lattice) % 1.0
        old_row = self.box.distance_row(i)
        new_row = self.box.distance_row(i, new_frac)
        if not all(c.ok(self.hist, i, new_row) for c in self.constraints):
            return False
        st.tested += 1
        trial = {lab: c.copy() for lab, c in self.hist.counts.items()}
        f = self.hist._factor
        for lab, c in self.hist._bin_rows(i, old_row).items():
            trial[lab] -= f(lab) * c
        for lab, c in self.hist._bin_rows(i, new_row).items():
            trial[lab] += f(lab) * c
        chi2_new = self._chi2(trial)
        delta = 0.5 * (chi2_new - self.chi2)
        for p in self.potentials:
            delta += p.energy_row(self.hist, i, new_row) - p.energy_row(self.hist, i, old_row)
        if delta > 0 and self.rng.random() >= math.exp(-delta):
            return False
        self.box.frac[i] = new_frac
        self.hist.counts = trial
        self.chi2 = chi2_new
        st.accepted += 1
        return True

    def run(self, n_moves, print_every=0, callback=None):
        for k in range(n_moves):
            self.step()
            if print_every and (k + 1) % print_every == 0:
                self.state.chi2_history.append((self.state.generated, self.chi2))
                print("moves %d tested %d accepted %d chi2 %.6g"
                      % (self.state.generated, self.state.tested, self.state.accepted, self.chi2))
                if callback:
                    callback(self)
        self.state.chi2_history.append((self.state.generated, self.chi2))
        return self.state


def synth_targets(box, rmax, dr, noise, rng):
    """Partials and Keen G(r) of `box` on RMCProfile's grid, plus Gaussian noise of s.d. `noise` on each partial."""
    h = Histogram(box, rmax, dr)
    parts = {lab: g + (rng.normal(0.0, noise, g.shape) if noise else 0.0) for lab, g in h.g().items()}
    cfg = rt.Rmc6f(atom_types=list(box.types), counts=list(box.counts))
    w = rt.neutron_weights(cfg)
    G = sum(w[lab] * (parts[lab] - 1.0) for lab in parts)
    return h.r, parts, G


