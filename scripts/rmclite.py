"""rmclite — a small, clean-room Reverse Monte Carlo engine for teaching.

Written from McGreevy & Pusztai, Mol. Simul. 1 (1988) 359 and Tucker et al.,
J. Phys.: Condens. Matter 19 (2007) 335218 (references/rmclite.md). It is a
teaching object: a few hundred to a few thousand atoms, single-atom moves,
partial g(r) on RMCProfile's grid, chi^2 over partial / total G(r) / F(Q)
targets, closest-approach and distance-window constraints, a harmonic bond
potential, Metropolis acceptance. It never claims RMCProfile's speed or
feature set; its calculated functions are RMCProfile's by construction
(same histogram, same weights: scripts/upstream_adapter.py proves it).

Usage:
    python scripts/rmclite.py synth CONFIG.rmc6f [--displace 0.15] [--noise 0.0] [--rmax 8] [--dr 0.02] [--seed 0] [--outdir OUT]
    python scripts/rmclite.py fit   CONFIG.rmc6f --target PARTIALS.csv [--gofr G.csv] [--moves 5000] [--sigma 0.2]
                                    [--min-dist "A-A:3.0,A-B:2.2"] [--max-move 0.05] [--rmax 8] [--dr 0.02] [--seed 0] [--outdir OUT]
    python scripts/rmclite.py --selftest
"""

