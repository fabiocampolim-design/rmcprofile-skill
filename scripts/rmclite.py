def parse_min_dist(text):
    out = {}
    for item in text.split(","):
        item = item.strip()
        if item:
            lab, val = item.split(":")
            out[lab.strip()] = float(val)
    return out


def _write_partials_csv(path, r, parts):
    labels = list(parts)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("   r (Ang), " + ", ".join("%9s" % lab for lab in labels) + "\n")
        for k in range(len(r)):
            f.write("%10.5f , " % r[k] + " , ".join("%.9f" % parts[lab][k] for lab in labels) + " , \n")


def _write_gofr_csv(path, r, G):
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("r (Ang), G(r) barn, G(r) barn\n")
        for k in range(len(r)):
            f.write("%12.6f , %16.9f , %16.9f\n" % (r[k], G[k], G[k]))


def _audit(log_dir, argv, ok, extra):
    os.makedirs(log_dir, exist_ok=True)
    stamp = _dt.datetime.now().strftime("%Y%m%dT%H%M%S%f")
    with open(os.path.join(log_dir, "rmclite_%s.json" % stamp), "w", encoding="utf-8") as f:
        json.dump({"tool": "rmclite", "version": rt.__version__, "argv": list(argv), "ok": bool(ok), **extra}, f, indent=2)


def _nacl_box(n=2, a=5.64):
    base = {"Na": [(0, 0, 0), (.5, .5, 0), (.5, 0, .5), (0, .5, .5)],
            "Cl": [(.5, 0, 0), (0, .5, 0), (0, 0, .5), (.5, .5, .5)]}
    atoms, frac = [], []
    for el in ("Na", "Cl"):
        for i, j, k in np.ndindex(n, n, n):
            for x, y, z in base[el]:
                atoms.append(el)
                frac.append([(x + i) / n, (y + j) / n, (z + k) / n])
    N = len(atoms)
    return Box(["Na", "Cl"], [N // 2, N // 2], n * a * np.eye(3), np.array(frac), np.array(atoms, dtype=object), N / (n * a) ** 3)


def selftest(outdir):
    """From the ideal 2x2x2 rock-salt lattice toward the partials of a thermally
    displaced copy (s.d. 0.05 A): chi2 must fall by 80 % in 2000 moves."""
    os.makedirs(outdir, exist_ok=True)
    rng = np.random.default_rng(1)
    truth = _nacl_box(2)
    truth.frac = (truth.frac + rng.normal(0, 0.05, truth.frac.shape) / 11.28) % 1.0
    r, parts, _ = synth_targets(truth, 5.0, 0.02, 0.0, rng)
    start = _nacl_box(2)
    eng = RmcLite(start, 5.0, 0.02, [PartialTarget(lab, r, parts[lab], 0.2) for lab in parts],
                  constraints=[ClosestApproach({"Na-Na": 3.0, "Na-Cl": 2.2, "Cl-Cl": 3.0})],
                  max_move={"Na": 0.05, "Cl": 0.05}, seed=3)
    chi0 = eng.chi2
    eng.run(2000)
    return [{"name": "synthetic recovery (2x2x2 NaCl, 2000 moves)", "ok": eng.chi2 < 0.2 * chi0,
             "detail": "chi2 %.3g -> %.3g" % (chi0, eng.chi2)}]


def build_parser():
    common = argparse.ArgumentParser(add_help=False)
    common.add_argument("--outdir", default="out", help="where outputs are written")
    common.add_argument("--log-dir", default="logs", help="where the JSON audit log is written")
    common.add_argument("-q", "--quiet", action="store_true", help="print only the verdict")
    common.add_argument("--rmax", type=float, default=8.0, help="largest r of the partials (below half the shortest cell edge)")
    common.add_argument("--dr", type=float, default=0.02, help="r step (Angstrom); RMCProfile's grid r_k = k*dr")
    common.add_argument("--seed", type=int, default=0, help="random seed")
    ap = argparse.ArgumentParser(prog="rmclite", description=__doc__.splitlines()[0], parents=[common])
    ap.add_argument("--version", action="version", version="rmcprofile-skill %s" % rt.__version__)
    ap.add_argument("--selftest", action="store_true", help="synthetic recovery on a small rock-salt box, exit 0/1")
    sub = ap.add_subparsers(dest="cmd")
    s = sub.add_parser("synth", help="displace a configuration and write target partials / G(r) of the original", parents=[common])
    s.add_argument("rmc6f")
    s.add_argument("--displace", type=float, default=0.15, help="Gaussian displacement s.d. (Angstrom) applied to every atom")
    s.add_argument("--noise", type=float, default=0.0, help="Gaussian noise s.d. added to each target partial")
    f = sub.add_parser("fit", help="run rmclite on a configuration against target partials (and optionally G(r))", parents=[common])
    f.add_argument("rmc6f")
    f.add_argument("--target", required=True, help="target _PDFpartials.csv (RMCProfile layout)")
    f.add_argument("--gofr", default=None, help="optional target G(r) CSV (r, G, G) in barn")
    f.add_argument("--moves", type=int, default=5000, help="moves to generate")
    f.add_argument("--sigma", type=float, default=0.2, help="sigma of every partial target (and of G(r) if given)")
    f.add_argument("--min-dist", default="", help="closest approach per pair, e.g. \"Na-Na:3.0,Na-Cl:2.2\"")
    f.add_argument("--max-move", type=float, default=0.05, help="largest displacement per move (Angstrom), all types")
    f.add_argument("--print-every", type=int, default=0, help="print chi2 every N moves (0 = only at the end)")
    return ap


def main(argv=None):
    argv = list(sys.argv[1:] if argv is None else argv)
    args = build_parser().parse_args(argv)
    if args.selftest:
        checks = selftest(args.outdir)
        ok = all(c["ok"] for c in checks)
        if not args.quiet:
            for c in checks:
                print("[%s] %s - %s" % ("PASS" if c["ok"] else "FAIL", c["name"], c["detail"]))
        _audit(args.log_dir, argv, ok, {"checks": checks})
        print("rmclite selftest: %s" % ("ALL CHECKS PASSED" if ok else "FAILED"))
        return 0 if ok else 1
    if args.cmd not in ("synth", "fit"):
        build_parser().print_help()
        return 2
    os.makedirs(args.outdir, exist_ok=True)
    cfg = rt.read_rmc6f(args.rmc6f)
    stem = os.path.splitext(os.path.basename(args.rmc6f))[0]
    rng = np.random.default_rng(args.seed)
    if args.cmd == "synth":
        ideal = Box.from_rmc6f(cfg)
        r, parts, G = synth_targets(ideal, args.rmax, args.dr, args.noise, rng)
        moved = Box.from_rmc6f(cfg)
        moved.frac = (moved.frac + rng.normal(0.0, args.displace, moved.frac.shape) @ np.linalg.inv(moved.lattice)) % 1.0
        moved.to_rmc6f(cfg).write(os.path.join(args.outdir, stem + "_displaced.rmc6f"))
        _write_partials_csv(os.path.join(args.outdir, stem + "_target_PDFpartials.csv"), r, parts)
        _write_gofr_csv(os.path.join(args.outdir, stem + "_target_GofR.csv"), r, G)
        rms = rms_displacement(moved, ideal)
        if not args.quiet:
            print("synth %s: %d atoms displaced (rms %.3f A), targets on %d r points -> %s" % (stem, moved.n, rms, len(r), args.outdir))
        _audit(args.log_dir, argv, True, {"rms_displacement": rms, "n_r": len(r)})
        return 0
    box = Box.from_rmc6f(cfg)
    r_t, parts_t = rt.read_partials_csv(args.target)
    targets = [PartialTarget(lab, r_t, parts_t[lab], args.sigma) for lab in parts_t]
    if args.gofr:
        r_g, G_t, _ = rt.read_csv_pair(args.gofr)
        targets.append(TotalGTarget(r_g, G_t, args.sigma, rt.neutron_weights(cfg)))
    constraints = [ClosestApproach(parse_min_dist(args.min_dist))] if args.min_dist else []
    rmax = r_t[-1] + 1e-9                         # the target grid fixes the histogram grid
    eng = RmcLite(box, rmax, float(np.round(np.diff(r_t).mean(), 6)), targets, constraints,
                  max_move={t: args.max_move for t in box.types}, seed=args.seed)
    chi0 = eng.chi2
    st = eng.run(args.moves, print_every=args.print_every)
    fit_stem = stem + "_fit"
    eng.box.to_rmc6f(cfg).write(os.path.join(args.outdir, fit_stem + ".rmc6f"))
    with open(os.path.join(args.outdir, fit_stem + ".chi2"), "w", encoding="utf-8", newline="\n") as f:
        f.write("m_accepted   m_generated   m_tested   chi2\n")
        for gen, chi in st.chi2_history:
            f.write(" %d   %d   %d   %.6g\n" % (st.accepted if gen == st.generated else 0, gen, st.tested if gen == st.generated else 0, chi))
    g = eng.hist.g()
    _write_partials_csv(os.path.join(args.outdir, fit_stem + "_PDFpartials.csv"), eng.hist.r, g)
    w = rt.neutron_weights(cfg)
    _write_gofr_csv(os.path.join(args.outdir, fit_stem + "_GofR.csv"), eng.hist.r, sum(w[lab] * (g[lab] - 1.0) for lab in g))
    if not args.quiet:
        print("fit %s: %d generated, %d tested, %d accepted, chi2 %.4g -> %.4g -> %s"
              % (stem, st.generated, st.tested, st.accepted, chi0, eng.chi2, args.outdir))
    _audit(args.log_dir, argv, True, {"chi2_start": chi0, "chi2_end": eng.chi2, "generated": st.generated, "accepted": st.accepted})
    return 0


if __name__ == "__main__":
    sys.exit(main())
